def annual_p(kind: str, value: float, years: float) -> float:
    if kind == "rate":
        return 1 - math.exp(-value)
    if kind == "cum":
        return 1 - (1 - value) ** (1 / years)
    return value


def disease_targets() -> dict:
    """每病的校準目標 = 各研究換算後一年復發機率的中位數；另回傳最小、最大值與研究數。"""
    import numpy as np
    out = {}
    for d in sorted({r[0] for r in RATES}):
        ps = [annual_p(k, v, y) for dd, _, k, v, y, _ in RATES if dd == d]
        out[d] = {"target": float(np.median(ps)), "lo": min(ps), "hi": max(ps), "k": len(ps), "values": ps}
    return out
