"""把條列（1. 2. …）改寫為段落敘述；另存新檔，原檔不動。
每組以第一項開頭定位並核對項數；改寫後的段落套用該文件一般內文段落的格式。
用法：python lists_to_prose.py <B原檔> <B新檔> <A原檔> <A新檔>"""
import copy
import re
import sys

import docx
from docx.oxml.ns import qn

B_SRC, B_DST, A_SRC, A_DST = sys.argv[1:5]


def apply(src, dst, groups, body_tmpl_start):
    d = docx.Document(src)
    tmpl = next(p for p in d.paragraphs if p.text.strip().startswith(body_tmpl_start))
    log = []
    for first, n_items, paras in groups:
        ps = d.paragraphs
        i = next(k for k, p in enumerate(ps) if p.text.strip().startswith(first))
        items = ps[i:i + n_items]
        for k, p in enumerate(items, 1):
            assert re.match(rf"^{k}[\.、．]", p.text.strip()), f"第 {k} 項不符：{p.text[:30]}"
        nxt = ps[i + n_items].text.strip() if i + n_items < len(ps) else ""
        assert not re.match(rf"^{n_items + 1}[\.、．]", nxt), f"條列不只 {n_items} 項：{first}"
        anchor = items[0]._p
        rpr = items[0].runs[0]._r.find(qn("w:rPr"))
        for text in paras:
            newp = copy.deepcopy(tmpl._p)
            for r in newp.findall(qn("w:r")):
                newp.remove(r)
            run = copy.deepcopy(items[0].runs[0]._r)
            for t in run.findall(qn("w:t")):
                run.remove(t)
            t = run.makeelement(qn("w:t"), {})
            t.text = text
            run.append(t)
            newp.append(run)
            anchor.addprevious(newp)
        for p in items:
            p._p.getparent().remove(p._p)
        log.append((first[:24], n_items, len(paras)))
    d.save(dst)
    return log


