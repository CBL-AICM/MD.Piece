def file_table(folder, filt=None, over=None):
    rows = ["| 檔案 | 修改時間（2026） | 說明 |", "|---|---|---|"]
    if not os.path.isdir(folder):
        return "（資料夾不存在）"
    ext_rank = {".md": 0, ".docx": 1, ".pdf": 2}
    order = lambda f: (os.path.splitext(f)[0], ext_rank.get(os.path.splitext(f)[1], 3))   # 同名之 md、Word、PDF 排在一起（「同上」才不會錯指）
    prev = None
    for f in sorted(os.listdir(folder), key=order):
        p = os.path.join(folder, f)
        if f.startswith("~$") or os.path.isdir(p) or (filt and not any(k in f for k in filt)):
            continue
        t = dt.datetime.fromtimestamp(os.path.getmtime(p), TW).strftime("%m-%d %H:%M")
        base, ext = os.path.splitext(f)
        note = (over or {}).get(f) or NOTES.get(f, "（依檔名與修改時間列出）")
        if note.startswith("同上") and prev != base:
            note = NOTES.get(base + ".md", "") + {".docx": "（Word）", ".pdf": "（PDF）"}.get(ext, "")
        prev = base
        rows.append(f"| {f} | {t} | {note} |")
    return "\n".join(rows)


