def tidy(text):
    """Word 表格欄寬由內容自動決定：短日期與二字類型會被擠成一字一行。
    錯誤表之「類型」併入「問題」；表內日期改用不斷行連字號（U+2011）。"""
    out = []
    for ln in text.splitlines():
        if ln.startswith("| 日期 | 類型 | 問題 |"):
            ln = "| 日期 | 問題 | 如何發現 | 更正與影響 | 提交 |"
        elif ln == "|---|---|---|---|---|---|" and out and out[-1].startswith("| 日期 | 問題 |"):
            ln = "|---|---|---|---|---|"
        else:
            m = re.match(r"^\| (\d\d)-(\d\d) \| ([^|]+?) \| (.*)$", ln)
            if m and ln.count("|") == 7:
                ln = f"| {m[1]}-{m[2]} | 〔{m[3]}〕{m[4]}"
        if ln.startswith("|"):
            ln = re.sub(r"\| (\d\d)-(\d\d) \|", lambda k: f"| {k[1]}\u2011{k[2]} |", ln)
        out.append(ln)
    return "\n".join(out)


